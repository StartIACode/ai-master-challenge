# --------------------------------------------------------------------------- helpers
def r4(x: float) -> float:
    return round(float(x), 4)


def r6(x: float) -> float:
    return round(float(x), 6)


def mean_or_none(values: np.ndarray) -> float | None:
    return r4(values.mean()) if values.size else None


def sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def peak_rss_mb() -> float:
    if resource is None:
        return 0.0
    rss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    if sys.platform != "darwin":  # Linux reports kilobytes, macOS bytes
        rss *= 1024
    return round(rss / 1e6, 1)


def pct(x: float) -> str:
    """pt-BR percentage for figure labels."""
    return f"{x:.1%}".replace(".", ",")


# --------------------------------------------------------------------------- data
def load_and_dedup() -> tuple[pd.DataFrame, int, int]:
    """Read Dataset 2 and drop near-duplicates keyed by the first ``DEDUP_WORDS`` words.

    The original 0-based row index is kept as the ticket ``id`` so every prediction
    can be traced back to the CSV line.
    """
    df = pd.read_csv(DATA, usecols=[TEXT_COL, LABEL_COL])
    df[TEXT_COL] = df[TEXT_COL].fillna("").astype(str)
    df[LABEL_COL] = df[LABEL_COL].astype(str)
    n_total = int(len(df))
    unknown = sorted(set(df[LABEL_COL]) - set(CLASSES))
    if unknown:
        sys.exit(f"unexpected classes in {DATA.name}: {unknown}")
    key = df[TEXT_COL].map(lambda s: " ".join(s.split()[:DEDUP_WORDS]))
    keep = ~key.duplicated(keep="first")
    df = df[keep & (df[TEXT_COL].str.strip() != "")]
    n_removed = n_total - int(len(df))
    return df, n_total, n_removed


def split(df: pd.DataFrame) -> tuple[np.ndarray, np.ndarray]:
    """Stratified 80/20 split; returns positional indices into ``df``."""
    positions = np.arange(len(df))
    tr, ho = train_test_split(
        positions, test_size=TEST_SIZE, stratify=df[LABEL_COL].to_numpy(), random_state=SEED
    )
    return np.sort(tr), np.sort(ho)


# --------------------------------------------------------------------------- model
def fit(texts: np.ndarray, labels: np.ndarray) -> tuple[TfidfVectorizer, LogisticRegression, sparse.csr_matrix]:
    vec = TfidfVectorizer(dtype=np.float32, **TFIDF_CONFIG)
    X = vec.fit_transform(texts).tocsr()
    # Older scikit-learn versions keep every pruned term here; it only bloats the pickle.
    if getattr(vec, "stop_words_", None) is not None:
        vec.stop_words_ = None
    clf = LogisticRegression(**LOGREG_CONFIG).fit(X, labels)
    if list(clf.classes_) != CLASSES:
        sys.exit(f"classifier classes {list(clf.classes_)} differ from policy.CLASSES {CLASSES}")
    return vec, clf, X


def predict(clf: LogisticRegression, X: sparse.csr_matrix) -> tuple[np.ndarray, np.ndarray, np.ndarray, list[list[dict]]]:
    proba = clf.predict_proba(X).astype(np.float64)
    order = np.argsort(-proba, axis=1)[:, :3]
    pred = clf.classes_[order[:, 0]]
    # Rounded once, here, so metrics.json and holdout_pred.csv.gz use identical numbers.
    confidence = np.round(proba.max(axis=1), 6)
    top3 = [
        [{"category": str(clf.classes_[j]), "p": r6(proba[i, j])} for j in order[i]]
        for i in range(proba.shape[0])
    ]
    return proba, pred, confidence, top3


def nearest_neighbors(
    X_query: sparse.csr_matrix,
    X_train: sparse.csr_matrix,
    k: int = TOP_K,
    block: int = SIM_BLOCK,
    chunk: int = SIM_CHUNK,
) -> tuple[np.ndarray, np.ndarray]:
    """Top-``k`` cosine neighbors (positions in ``X_train``) computed ``block`` rows at a time.

    TF-IDF rows are already L2-normalized, so the dot product is the cosine. The
    similarity of one block is ~86% dense on this dataset, so it lives in a reused
    dense float32 buffer (block x n_train). The sparse product and the top-k are
    done ``chunk`` rows at a time inside the block: scipy sizes the product by an
    nnz upper bound and ``argpartition`` allocates an int64 index array, and both
    scale with the number of rows. Measured on this dataset: peak RSS 1.3 GB with
    chunk=125 versus 3.3 GB for a plain 2,000-row sparse product, same 6-7 s.
    """
    n, n_train = X_query.shape[0], X_train.shape[0]
    nn_pos = np.zeros((n, k), dtype=np.int64)
    nn_sim = np.zeros((n, k), dtype=np.float32)
    X_train_t = X_train.T.tocsr()
    buffer = np.empty((min(block, n), n_train), dtype=np.float32)
    for start in range(0, n, block):
        stop = min(start + block, n)
        S = buffer[: stop - start]
        for c in range(0, stop - start, chunk):
            prod = X_query[start + c:min(start + c + chunk, stop)] @ X_train_t
            prod.toarray(out=S[c:c + prod.shape[0]])
        for c in range(0, stop - start, chunk):
            Sc = S[c:c + chunk]
            idx = np.argpartition(Sc, n_train - k, axis=1)[:, -k:]  # k largest, unordered
            sims = np.take_along_axis(Sc, idx, axis=1)
            order = np.argsort(-sims, axis=1, kind="stable")
            nn_pos[start + c:start + c + Sc.shape[0]] = np.take_along_axis(idx, order, axis=1)
            nn_sim[start + c:start + c + Sc.shape[0]] = np.take_along_axis(sims, order, axis=1)
    return nn_pos, np.clip(nn_sim, 0.0, 1.0)


# --------------------------------------------------------------------------- metrics
def per_class_report(y_true: np.ndarray, y_pred: np.ndarray) -> dict:
    rep = classification_report(y_true, y_pred, labels=CLASSES, output_dict=True, zero_division=0)
    return {
        c: {
            "precision": r4(rep[c]["precision"]),
            "recall": r4(rep[c]["recall"]),
            "f1": r4(rep[c]["f1-score"]),
            "support": int(rep[c]["support"]),
        }
        for c in CLASSES
    }


def expected_calibration_error(confidence: np.ndarray, correct: np.ndarray, n_bins: int = ECE_BINS) -> tuple[float, list[dict]]:
    """Equal-width ECE: sum_b (n_b / N) * |acc_b - conf_b|."""
    edges = np.linspace(0.0, 1.0, n_bins + 1)
    which = np.minimum((confidence * n_bins).astype(int), n_bins - 1)
    n = confidence.size
    ece = 0.0
    bins = []
    for b in range(n_bins):
        m = which == b
        nb = int(m.sum())
        row = {"lo": r4(edges[b]), "hi": r4(edges[b + 1]), "n": nb, "confidence": None, "accuracy": None}
        if nb:
            conf_b = float(confidence[m].mean())
            acc_b = float(correct[m].mean())
            ece += nb / n * abs(acc_b - conf_b)
            row.update(confidence=r4(conf_b), accuracy=r4(acc_b))
        bins.append(row)
    return r4(ece), bins


def threshold_curve(confidence: np.ndarray, correct: np.ndarray, pred: np.ndarray, has_risk: np.ndarray) -> list[dict]:
    """Raw and useful (policy-filtered) coverage x accuracy for every threshold."""
    n = confidence.size
    auto_ok = np.isin(pred, list(AUTO)) & ~has_risk
    rows = []
    for t in THRESHOLDS:
        covered = confidence >= t
        useful = covered & auto_ok
        rest = ~covered
        rows.append(
            {
                "t": float(t),
                "coverage": r4(covered.mean()),
                "n_covered": int(covered.sum()),
                "acc_covered": mean_or_none(correct[covered]),
                "n_errors_covered": int((~correct[covered]).sum()),
                "acc_rest": mean_or_none(correct[rest]),
                "n_rest": int(rest.sum()),
                "useful_coverage": r4(useful.sum() / n),
                "n_useful": int(useful.sum()),
                "useful_acc": mean_or_none(correct[useful]),
                "n_errors_useful": int((~correct[useful]).sum()),
            }
        )
    return rows


def per_class_at_thresholds(confidence: np.ndarray, correct: np.ndarray, pred: np.ndarray, y_true: np.ndarray) -> dict:
    """Per predicted class: share of its tickets above the threshold and their accuracy."""
    n = confidence.size
    out: dict[str, dict] = {}
    for t in POLICY_THRESHOLDS:
        table = {}
        for c in CLASSES:
            is_pred = pred == c
            covered = is_pred & (confidence >= t)
            n_pred = int(is_pred.sum())
            n_cov = int(covered.sum())
            table[c] = {
                "coverage": r4(n_cov / n_pred) if n_pred else 0.0,
                "acc": mean_or_none(correct[covered]),
                "n": n_cov,
                "n_pred": n_pred,
                "support": int((y_true == c).sum()),
                "n_errors": int((~correct[covered]).sum()),
                "share_of_all": r4(n_cov / n),
            }
        out[f"{t:.2f}"] = table
    return out


def similarity_metrics(nn_pos: np.ndarray, nn_sim: np.ndarray, y_train: np.ndarray, y_true: np.ndarray) -> dict:
    sim1 = nn_sim[:, 0].astype(np.float64)
    nn_correct = y_train[nn_pos[:, 0]] == y_true
    bins = []
    for b in SIM_BINS:
        m = sim1 >= b
        bins.append(
            {
                "min_sim": b,
                "coverage": r4(m.mean()),
                "n": int(m.sum()),
                "nn_agreement": mean_or_none(nn_correct[m]),
            }
        )
    return {
        "k": TOP_K,
        "nn_accuracy": r4(nn_correct.mean()),
        "sim1_mean": r4(sim1.mean()),
        "sim1_median": r4(np.median(sim1)),
        "bins": bins,
    }


def cross_validate_5fold(texts: np.ndarray, labels: np.ndarray) -> dict:
    pipe = Pipeline(
        [("tfidf", TfidfVectorizer(dtype=np.float32, **TFIDF_CONFIG)), ("clf", LogisticRegression(**LOGREG_CONFIG))]
    )
    cv = StratifiedKFold(n_splits=CV_FOLDS, shuffle=True, random_state=SEED)
    t0 = time.perf_counter()
    res = cross_validate(pipe, texts, labels, cv=cv, scoring=("accuracy", "f1_macro"), n_jobs=1)
    return {
        "folds": CV_FOLDS,
        "accuracy": r4(res["test_accuracy"].mean()),
        "accuracy_std": r4(res["test_accuracy"].std()),
        "macro_f1": r4(res["test_f1_macro"].mean()),
        "macro_f1_std": r4(res["test_f1_macro"].std()),
        "fold_accuracies": [r4(s) for s in res["test_accuracy"]],
        "seconds": r4(time.perf_counter() - t0),
    }


