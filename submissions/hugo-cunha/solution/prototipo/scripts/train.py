def _style(ax, title: str, subtitle: str, xlabel: str, ylabel: str) -> None:
    ax.set_title(title, loc="left", fontsize=11.5, color=INK, pad=20)
    ax.text(0, 1.02, subtitle, transform=ax.transAxes, ha="left", va="bottom", fontsize=8.5, color=GRAY)
    ax.set_xlabel(xlabel, color=INK)
    ax.set_ylabel(ylabel, color=INK)
    ax.grid(color=GRID, linewidth=0.6)
    ax.set_axisbelow(True)
    for side in ("top", "right"):
        ax.spines[side].set_visible(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_color(GRAY)
    ax.tick_params(colors=INK, labelsize=8.5)


def _new_figure(size=(9, 5.2)):
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=size, dpi=150)
    fig.patch.set_facecolor(SURFACE)
    ax.set_facecolor(SURFACE)
    return plt, fig, ax


def _save(plt, fig, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.tight_layout()
    fig.savefig(path, facecolor=SURFACE)
    plt.close(fig)


def plot_confusion(matrix: np.ndarray, accuracy: float, n: int) -> None:
    from matplotlib.colors import LinearSegmentedColormap

    plt, fig, ax = _new_figure((8.6, 7.2))
    row_sums = matrix.sum(axis=1, keepdims=True)
    norm = np.divide(matrix, row_sums, out=np.zeros_like(matrix, dtype=float), where=row_sums > 0)
    cmap = LinearSegmentedColormap.from_list("navy_seq", [SURFACE, NAVY])
    ax.imshow(norm, cmap=cmap, vmin=0, vmax=1)
    k = len(CLASSES)
    ax.set_xticks(range(k), CLASSES, rotation=35, ha="right")
    ax.set_yticks(range(k), CLASSES)
    for i in range(k):
        for j in range(k):
            if matrix[i, j] == 0:
                continue
            color = SURFACE if norm[i, j] > 0.55 else INK
            ax.text(j, i, f"{norm[i, j]:.0%}\n{matrix[i, j]:,}".replace(",", "."), ha="center", va="center",
                    fontsize=7.5, color=color)
    n_txt = f"{n:,}".replace(",", ".")
    _style(ax, "Matriz de confusão do hold-out (normalizada por linha)",
           f"acurácia {pct(accuracy)} · n = {n_txt} tickets · linha = classe verdadeira, coluna = prevista",
           "classe prevista", "classe verdadeira")
    ax.grid(False)
    for side in ("left", "bottom"):
        ax.spines[side].set_visible(False)
    _save(plt, fig, FIGURES["confusion"])


def plot_coverage_accuracy(rows: list[dict]) -> None:
    plt, fig, ax = _new_figure()
    cov = [r["coverage"] for r in rows]
    acc = [r["acc_covered"] for r in rows]
    ucov = [r["useful_coverage"] for r in rows]
    uacc = [r["useful_acc"] for r in rows]
    ax.plot(cov, acc, color=NAVY, linewidth=2, marker="o", markersize=3.5, label="cobertura bruta (p ≥ limiar)")
    ax.plot(ucov, uacc, color=GOLD, linewidth=2, marker="s", markersize=3.5,
            label="cobertura útil (p ≥ limiar, classe AUTO, sem sinal de risco)")
    for t in POLICY_THRESHOLDS:
        r = next(x for x in rows if abs(x["t"] - t) < 1e-9)
        label = f"limiar {t:.2f}".replace(".", ",")
        # raw series: label above-right; useful series: below-left, so labels never cross the other line
        for x, y, xytext, ha in ((r["coverage"], r["acc_covered"], (7, 7), "left"),
                                 (r["useful_coverage"], r["useful_acc"], (-8, -12), "right")):
            ax.annotate(label, (x, y), textcoords="offset points", xytext=xytext, ha=ha, fontsize=8, color=INK)
            ax.plot([x], [y], marker="o", markersize=8, markerfacecolor="none", markeredgecolor=DANGER, linewidth=0)
    ax.text(cov[0], acc[0], "  bruta", color=NAVY, fontsize=8.5, va="center")
    ax.text(ucov[0], uacc[0], "  útil", color=GOLD, fontsize=8.5, va="center")
    ax.set_xlim(0, 1)
    lo = min(min(a for a in acc if a is not None), min(a for a in uacc if a is not None))
    ax.set_ylim(max(0.0, lo - 0.03), 1.005)
    ax.xaxis.set_major_formatter(lambda v, _: f"{v:.0%}")
    ax.yaxis.set_major_formatter(lambda v, _: f"{v:.0%}")
    ax.legend(loc="lower left", frameon=False, fontsize=8.5)
    _style(ax, "Cobertura × acerto por limiar de confiança",
           "hold-out · cada ponto é um limiar de 0,50 a 0,99 · círculos vermelhos: 0,80 / 0,90 / 0,95",
           "fração dos tickets roteados sozinhos pela IA", "acerto entre os tickets roteados")
    _save(plt, fig, FIGURES["coverage_accuracy"])


